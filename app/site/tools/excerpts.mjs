// Pull real code and measured benchmarks out of the library (the repo root: src/, README.md) into site/src/data/oss.js,
// so the site never shows code or numbers that the library doesn't contain. Run in app/ before `npm run build`:
//   node site/tools/excerpts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..'); // app/
const oss = path.resolve(root, '..');                                               // the library at the repo root
const read = (f) => { try { return fs.readFileSync(path.join(oss, f), 'utf8'); } catch { return null; } };

function excerpt(file, startRe, endRe, max = 30) {
  const src = read(file); if (!src) return null;
  const lines = src.split('\n');
  const a = lines.findIndex((l) => startRe.test(l)); if (a < 0) return null;
  let b = lines.findIndex((l, i) => i > a && endRe.test(l)); if (b < 0) b = Math.min(lines.length - 1, a + max);
  b = Math.min(b, a + max - 1);
  return { file, from: a + 1, to: b + 1, code: lines.slice(a, b + 1).join('\n') };
}

const out = {
  idclock: excerpt('src/idclock.js', /^export function idToDate/, /return \{ at: new Date\(lerp\(lo, hi, id\)\), exact: false, source: 'local'/, 18),
  index: excerpt('src/index.js', /^export \{ survey/, /^export \{ StarcropError/, 12),
  rows: excerpt('src/analyze.js', /---- plantingRows/, /const rowAgreement/, 22),
  bench: [], benchCmd: null, benchMachine: null,
};

// Benchmarks: the first markdown table after a heading containing "Bench" in the library README.md
const readme = read('README.md');
if (readme) {
  const lines = readme.split('\n');
  const h = lines.findIndex((l) => /^#{2,3} .*bench/i.test(l));
  if (h >= 0) {
    const sect = []; for (let i = h + 1; i < lines.length && !/^#{1,3} /.test(lines[i]); i++) sect.push(lines[i]);
    const rows = sect.filter((l) => /^\|/.test(l) && !/^\|\s*-/.test(l)).map((l) => l.split('|').slice(1, -1).map((c) => c.trim().replace(/`/g, '')));
    if (rows.length > 1) { out.benchHead = rows[0]; out.bench = rows.slice(1); }
    // or a fenced block of `label: value` lines, as bench/bench.js prints them
    const fence = sect.join('\n').match(/```[a-z]*\n([\s\S]*?)```/)?.[1];
    if (out.bench.length === 0 && fence) {
      const kv = fence.split('\n').map((l) => l.match(/^(.*?):\s+(.+)$/)).filter(Boolean);
      const meta = Object.fromEntries(kv.filter((m) => /^(machine|date)$/.test(m[1])).map((m) => [m[1], m[2]]));
      out.bench = kv.filter((m) => !/^(machine|date)$/.test(m[1])).map((m) => [m[1], m[2]]);
      out.benchHead = ['Measurement', 'Result'];
      if (meta.machine) out.benchMachine = `${meta.machine}${meta.date ? ` · ${meta.date}` : ''}`;
      // the brass disc: three short stamps, each a number printed by the bench (<= 20 chars)
      const pick = (re, fmt) => { const r = out.bench.find((b) => re.test(b[0])); return r ? fmt(r) : null; };
      out.disc = [
        pick(/^analyze\(\) ClashDesk/, (r) => `ANALYZE ${r[1].match(/[\d,]+/)[0]}/S`),
        pick(/^idToDate\(\) global/, (r) => `IDTODATE ${r[1].match(/[\d,]+/)[0]}/S`),
        pick(/^survey\(\) live .*GROWN/, (r) => `SURVEY ${r[1].match(/median ([\d,]+ ms)/)[1].toUpperCase()}`),
      ].filter(Boolean);
    }
    const cmd = sect.find((l) => /^\s*(npm run bench|node bench)/.test(l)) || sect.join('\n').match(/`((?:npm run bench|node bench)[^`]*)`/)?.[1];
    if (cmd) out.benchCmd = cmd.trim();
    const mach = sect.find((l) => /Apple|MacBook|Mac mini|Node\s*\d|M\d/.test(l) && !/^\|/.test(l));
    if (mach && !out.benchMachine) out.benchMachine = mach.replace(/^[*>\-\s]+/, '').trim();
  }
}
fs.writeFileSync(path.join(root, 'site/src/data/oss.js'), `// generated by site/tools/excerpts.mjs from the library (repo root) — do not edit\nexport default ${JSON.stringify(out, null, 1)};\n`);
console.log('excerpts:', Object.entries(out).map(([k, v]) => `${k}=${v == null ? 'none' : Array.isArray(v) ? v.length : 'ok'}`).join(' '));
